const http = require('http');
const crypto = require('crypto');
const fs = require('fs');

http.get('http://127.0.0.1:9222/json', (res) => {
  let body = '';
  res.on('data', chunk => body += chunk);
  res.on('end', () => {
    let list;
    try {
      list = JSON.parse(body);
    } catch (e) {
      console.error('Failed to parse CDP JSON:', e);
      process.exit(1);
    }
    const page = list.find(p => p.type === 'page');
    if (!page) { console.error('No page found'); process.exit(1); }

    const wsUrl = new URL(page.webSocketDebuggerUrl);
    const key = crypto.randomBytes(16).toString('base64');
    const req = http.request({
      hostname: wsUrl.hostname,
      port: wsUrl.port,
      path: wsUrl.pathname,
      headers: {
        'Connection': 'Upgrade',
        'Upgrade': 'websocket',
        'Sec-WebSocket-Key': key,
        'Sec-WebSocket-Version': '13'
      }
    });

    req.on('upgrade', (res, socket, head) => {
      let nextId = 1;
      function send(method, params = {}) {
        const id = nextId++;
        const json = JSON.stringify({ id, method, params });
        const len = Buffer.byteLength(json);
        let header;
        if (len < 126) header = Buffer.from([0x81, 0x80 | len]);
        else if (len < 65536) {
          header = Buffer.alloc(4); header[0] = 0x81; header[1] = 0x80 | 126; header.writeUInt16BE(len, 2);
        } else {
          header = Buffer.alloc(10); header[0] = 0x81; header[1] = 0x80 | 127; header.writeBigUInt64BE(BigInt(len), 2);
        }
        const mask = crypto.randomBytes(4);
        const payload = Buffer.from(json);
        for (let i = 0; i < payload.length; i++) payload[i] ^= mask[i % 4];
        socket.write(Buffer.concat([header, mask, payload]));
        return id;
      }

      send('Console.enable');
      send('Runtime.enable');

      const consoleErrors = [];

      const evalId = send('Runtime.evaluate', {
        expression: `
          (async () => {
            const renamer = window.renamerUI;
            if (!renamer) return JSON.stringify({ error: 'window.renamerUI not found' });

            // 1. Open Settings modal
            renamer.handleOpenSettingsModal('presets');
            const modalSettings = document.getElementById('modalSettings');
            const isSettingsOpen = modalSettings && !modalSettings.classList.contains('hidden');

            // 2. Open Add Document modal from Presets
            renamer.openAddDocumentModal(null, false);
            const modalAddDoc = document.getElementById('modalAddDocument');
            const isAddDocOpen = modalAddDoc && !modalAddDoc.classList.contains('hidden');

            // 3. Verify Short Codes container is visible
            const containerCode = document.getElementById('containerAddDocCode');
            const isCodeContainerVisible = containerCode && !containerCode.classList.contains('hidden');

            // 4. Verify Preset Pills
            const containerPills = document.getElementById('containerPresetPills');
            const pillButtons = containerPills ? containerPills.querySelectorAll('button') : [];
            const pillCount = pillButtons.length;
            const activePresetPreselected = renamer._selectedPresetKeys && renamer._selectedPresetKeys.has(renamer.state.activePreset);

            // 5. Verify Keywords mandatory state & validation
            const inputName = document.getElementById('inputAddDocName');
            const inputAliases = document.getElementById('inputAddDocAliases');
            const btnSave = document.getElementById('btnSaveAddDoc');
            const btnAutoKw = document.getElementById('btnAutoGenerateKeywords');
            const isSaveDisabledInitially = btnSave ? btnSave.disabled : false;

            // 6. Test Live Auto-Generation of Smart Keywords
            inputName.value = '12TH MARKSHEET';
            inputName.dispatchEvent(new Event('input'));
            const autoGeneratedKws = inputAliases ? inputAliases.value : '';
            const isSaveEnabledAfterAuto = btnSave ? !btnSave.disabled : false;

            // 7. Toggle a second preset pill (CET CELL)
            if (pillButtons.length > 1) {
              const cetPill = Array.from(pillButtons).find(p => p.textContent.includes('CET CELL'));
              if (cetPill) cetPill.click();
            }
            const hasCetCellSelected = renamer._selectedPresetKeys && renamer._selectedPresetKeys.has('CET CELL');

            // 8. Save Document Type
            renamer.handleSaveDocumentType();

            // Verify document exists in shortcuts21
            const inShortcuts = renamer.shortcuts21.some(s => s.canonical === '12TH MARKSHEET');
            const inMahaDbt = (renamer.state.documentPresets['MAHA DBT'] || []).some(d => d.name === '12TH MARKSHEET');
            const inCetCell = (renamer.state.documentPresets['CET CELL'] || []).some(d => d.name === '12TH MARKSHEET');

            // Re-open modal to capture screenshot of the clean interactive state
            renamer.openAddDocumentModal({
              name: '12TH MARKSHEET',
              code: '12M',
              codes: ['12M'],
              keywords: autoGeneratedKws
            }, false);

            return JSON.stringify({
              isSettingsOpen,
              isAddDocOpen,
              isCodeContainerVisible,
              pillCount,
              activePresetPreselected,
              hasAutoKeywordsButton: !!btnAutoKw,
              isSaveDisabledInitially,
              autoGeneratedKeywordsSample: autoGeneratedKws.substring(0, 60),
              isSaveEnabledAfterAuto,
              hasCetCellSelected,
              inShortcuts,
              inMahaDbt,
              inCetCell
            });
          })()
        `,
        awaitPromise: true,
        returnByValue: true
      });

      let screenshotId = null;
      let buf = Buffer.alloc(0);

      socket.on('data', (chunk) => {
        buf = Buffer.concat([buf, chunk]);
        while (buf.length >= 2) {
          const payloadLen = buf[1] & 0x7f;
          let offset = 2;
          let len = payloadLen;
          if (payloadLen === 126) {
            if (buf.length < 4) break;
            len = buf.readUInt16BE(2); offset = 4;
          } else if (payloadLen === 127) {
            if (buf.length < 10) break;
            len = Number(buf.readBigUInt64BE(2)); offset = 10;
          }
          if (buf.length < offset + len) break;
          const payload = buf.slice(offset, offset + len);
          buf = buf.slice(offset + len);

          try {
            const resp = JSON.parse(payload.toString('utf8'));
            if (resp.method === 'Console.messageAdded' && resp.params?.message?.level === 'error') {
              consoleErrors.push(resp.params.message.text);
            }
            if (resp.method === 'Runtime.exceptionThrown') {
              consoleErrors.push(resp.params.exceptionDetails?.text || 'Exception');
            }

            if (resp.id === evalId) {
              console.log('--- DUAL-MCP LIVE VERIFICATION RESULT ---');
              console.log(resp.result?.result?.value);
              setTimeout(() => {
                screenshotId = send('Page.captureScreenshot', { format: 'png' });
              }, 700);
            } else if (resp.id === screenshotId) {
              const base64Data = resp.result.data;
              const artifactPath = 'C:/Users/USER/.gemini/antigravity/brain/12ea5c70-446e-4ca0-b1ea-4c628e4aaf83/settings_unified_sync_verification.png';
              fs.writeFileSync(artifactPath, Buffer.from(base64Data, 'base64'));
              console.log('Saved screenshot to:', artifactPath);
              console.log('Console Errors:', consoleErrors.length, consoleErrors);
              socket.end();
              process.exit(consoleErrors.length > 0 ? 1 : 0);
            }
          } catch (e) {
            console.error(e);
          }
        }
      });
    });
    req.end();
  });
});
